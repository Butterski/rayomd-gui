"""Writes src/text/unicode_tables.inc from the Unicode Character Database 16.0.0.

Tables, each sorted and of merged ranges or sorted pairs:
  kWideRanges       East_Asian_Width W or F (two editor cells)
  kZeroWidthRanges  General_Category Mn, Me or Cf, except U+00AD (no cell)
  kWhiteSpaceRanges the White_Space property
  kToUpper, kToLower simple case mappings (UnicodeData.txt fields 12 and 13)

Usage: scripts/generate_unicode_tables.py [--ucd DIR]
Without --ucd the files are downloaded from https://www.unicode.org/Public/16.0.0/ucd/.
"""

import argparse
import pathlib
import sys
import urllib.request

VERSION = "16.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
FILES = {
    "EastAsianWidth.txt": "EastAsianWidth.txt",
    "DerivedGeneralCategory.txt": "extracted/DerivedGeneralCategory.txt",
    "PropList.txt": "PropList.txt",
    "UnicodeData.txt": "UnicodeData.txt",
}
LICENSE_URL = "https://www.unicode.org/license.txt"
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "text" / "unicode_tables.inc"


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8")


def read(name, ucd):
    if ucd:
        return (pathlib.Path(ucd) / name).read_text(encoding="utf-8")
    return fetch(BASE + FILES[name])


def property_ranges(text):
    """Yields (first, last, value) of every 'XXXX..YYYY ; Value' line."""
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = (part.strip() for part in line.split(";")[:2])
        if ".." in cps:
            first, last = (int(x, 16) for x in cps.split(".."))
        else:
            first = last = int(cps, 16)
        yield first, last, value


def merge(ranges):
    merged = []
    for first, last in sorted(ranges):
        if merged and first <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], last)
        else:
            merged.append([first, last])
    return merged


def subtract(ranges, cp):
    out = []
    for first, last in ranges:
        if first <= cp <= last:
            if first < cp:
                out.append([first, cp - 1])
            if cp < last:
                out.append([cp + 1, last])
        else:
            out.append([first, last])
    return out


def range_table(name, ranges):
    lines = [f"inline constexpr CodepointRange {name}[] = {{"]
    row = []
    for first, last in ranges:
        row.append(f"{{0x{first:X}, 0x{last:X}}}")
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def pair_table(name, pairs):
    lines = [f"inline constexpr CaseMapping {name}[] = {{"]
    row = []
    for source, target in pairs:
        row.append(f"{{0x{source:X}, 0x{target:X}}}")
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ucd", help="a directory holding the four UCD files and license.txt")
    args = parser.parse_args()

    wide = [(f, l) for f, l, v in property_ranges(read("EastAsianWidth.txt", args.ucd)) if v in ("W", "F")]
    zero = [(f, l) for f, l, v in property_ranges(read("DerivedGeneralCategory.txt", args.ucd))
            if v in ("Mn", "Me", "Cf")]
    space = [(f, l) for f, l, v in property_ranges(read("PropList.txt", args.ucd)) if v == "White_Space"]

    upper, lower = [], []
    for line in read("UnicodeData.txt", args.ucd).splitlines():
        fields = line.split(";")
        if len(fields) < 15:
            continue
        cp = int(fields[0], 16)
        if fields[12]:
            upper.append((cp, int(fields[12], 16)))
        if fields[13]:
            lower.append((cp, int(fields[13], 16)))

    if args.ucd:
        license_text = (pathlib.Path(args.ucd) / "license.txt").read_text(encoding="utf-8")
    else:
        license_text = fetch(LICENSE_URL)
    notice = "\n".join(("// " + line).rstrip() for line in license_text.strip().splitlines())

    parts = [
        "// SPDX-License-Identifier: Unicode-3.0",
        f"// Generated by scripts/generate_unicode_tables.py from the Unicode Character Database {VERSION}",
        "// (EastAsianWidth.txt, extracted/DerivedGeneralCategory.txt, PropList.txt, UnicodeData.txt).",
        "// Do not edit by hand. The data files are covered by this notice:",
        "//",
        notice,
        "",
        "// Wide or fullwidth: two cells.",
        range_table("kWideRanges", merge(wide)),
        "",
        "// Nonspacing and enclosing marks and format characters, U+00AD excepted: no cell.",
        range_table("kZeroWidthRanges", subtract(merge(zero), 0xAD)),
        "",
        "// White_Space.",
        range_table("kWhiteSpaceRanges", merge(space)),
        "",
        "// Simple uppercase and lowercase mappings, sorted by source.",
        pair_table("kToUpper", sorted(upper)),
        "",
        pair_table("kToLower", sorted(lower)),
        "",
    ]
    OUTPUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
