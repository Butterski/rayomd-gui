"""Writes src/platform/linux/keysyms.inc from libxkbcommon's xkbcommon-keysyms.h.

The output has three sorted tables for src/platform/linux/xkb_keymap.cpp:
  kKeysymNames  name -> keysym, every XKB_KEY_* name (aliases included), sorted by name;
  kKeysymChars  keysym -> code point, from the "U+XXXX" and "<U+XXXX>" comments, for the
                keysyms the rules do not cover (Latin-1 keysyms are their code point, 0x01000000 +
                cp is a Unicode keysym), sorted by keysym;
  kCharKeysyms  code point -> keysym, the lowest legacy keysym whose comment is exactly "U+XXXX",
                sorted by code point (for the Caps Lock transformation).
Comments in parentheses "(U+XXXX ...)" mark deprecated approximate mappings and are skipped.

Usage: scripts/generate_keysyms.py [--header PATH] [--version VERSION] [--output PATH]
The version defaults to `pkg-config --modversion xkbcommon`.
"""

import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFINE = re.compile(r"^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+|_EVDEVK\((0x[0-9a-fA-F]+)\))\s*(.*)$")
UNICODE = re.compile(r"^/\*\s*(<?)U\+([0-9A-Fa-f]{4,6})\b")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", default="/usr/include/xkbcommon/xkbcommon-keysyms.h")
    parser.add_argument("--version")
    parser.add_argument("--output", default=str(ROOT / "src/platform/linux/keysyms.inc"))
    args = parser.parse_args()

    version = args.version
    if not version:
        version = subprocess.run(["pkg-config", "--modversion", "xkbcommon"], check=True,
                                 capture_output=True, text=True).stdout.strip()
    text = pathlib.Path(args.header).read_text(encoding="utf-8")

    notice_start = text.index("/******")
    notice_end = text.index("******/", notice_start) + len("******/")
    notice = text[notice_start:notice_end]
    notice = notice.strip("/*").strip("*").strip("\n")

    names = {}
    chars = {}
    exact = {}
    for line in text.splitlines():
        match = DEFINE.match(line)
        if not match:
            continue
        name = match.group(1)
        value = int(match.group(3), 16) + 0x10081000 if match.group(3) else int(match.group(2), 16)
        if name in names:
            sys.exit(f"duplicate keysym name {name}")
        names[name] = value
        comment = UNICODE.match(match.group(4).strip())
        if not comment:
            continue
        cp = int(comment.group(2), 16)
        if value not in chars:
            chars[value] = cp
        if not comment.group(1) and 0x100 <= value < 0x01000000 and (cp not in exact or value < exact[cp]):
            exact[cp] = value

    def covered(keysym, cp):
        if 0x20 <= keysym <= 0x7E or 0xA0 <= keysym <= 0xFF:
            return keysym == cp
        if 0x01000000 <= keysym <= 0x0110FFFF:
            return keysym - 0x01000000 == cp
        return False

    out = []
    out.append(f"// Generated by scripts/generate_keysyms.py from xkbcommon-keysyms.h of libxkbcommon {version};")
    out.append("// do not edit. The keysym names and values come from that header, which carries this notice:")
    out.append("//")
    for line in notice.splitlines():
        out.append(("// " + line).rstrip())
    out.append("")
    out.append("// Every keysym name, sorted by name (byte order).")
    out.append("static const KeysymName kKeysymNames[] = {")
    for name in sorted(names, key=lambda n: n.encode()):
        out.append(f'    {{"{name}", 0x{names[name]:x}}},')
    out.append("};")
    out.append("")
    out.append("// Keysym -> code point where Latin-1 and Unicode keysyms do not already say it, by keysym.")
    out.append("static const KeysymChar kKeysymChars[] = {")
    for keysym in sorted(chars):
        if not covered(keysym, chars[keysym]):
            out.append(f"    {{0x{keysym:x}, 0x{chars[keysym]:x}}},")
    out.append("};")
    out.append("")
    out.append("// Code point -> its lowest legacy keysym (exact mappings only), by code point.")
    out.append("static const KeysymChar kCharKeysyms[] = {")
    for cp in sorted(exact):
        if not (0x20 <= cp <= 0x7E or 0xA0 <= cp <= 0xFF):
            out.append(f"    {{0x{exact[cp]:x}, 0x{cp:x}}},")
    out.append("};")
    pathlib.Path(args.output).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{args.output}: {len(names)} names, libxkbcommon {version}")


if __name__ == "__main__":
    main()
