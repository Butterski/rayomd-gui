"""Writes src/ui/omarchy_themes.inc: Omarchy's built-in themes at one commit of omacom/omarchy.

For every directory in themes/ it takes colors.toml (required), shell.toml when the theme ships
one, the window rounding from hyprland.lua (`rounding = N`) and whether light.mode exists.
The material is MIT licensed (third_party/omarchy/LICENSE).

    scripts/import_omarchy_themes.py --commit 246f33a2fef66411c990860d88e0823ae83987fc

Set GITHUB_TOKEN when the anonymous API rate limit is reached.
"""

import argparse
import json
import os
import pathlib
import re
import sys
import urllib.request

REPO = "omacom/omarchy"
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "ui" / "omarchy_themes.inc"
DELIMITER = "rgui"


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "rayomd-gui-import"})
    token = os.environ.get("GITHUB_TOKEN")
    if token and url.startswith("https://api.github.com/"):
        request.add_header("Authorization", "Bearer " + token)
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def raw_file(commit, path):
    return fetch(f"https://raw.githubusercontent.com/{REPO}/{commit}/{path}").decode("utf-8")


def listing(commit, path):
    data = fetch(f"https://api.github.com/repos/{REPO}/contents/{path}?ref={commit}")
    return json.loads(data)


def display_name(slug):
    return " ".join(word[:1].upper() + word[1:] for word in slug.replace("-", " ").split(" "))


def literal(text):
    if ")" + DELIMITER + '"' in text:
        sys.exit(f"the raw string delimiter occurs in a theme file")
    return f'R"{DELIMITER}({text}){DELIMITER}"'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--commit", required=True, help="the omacom/omarchy commit to import")
    args = parser.parse_args()
    if not re.fullmatch(r"[0-9a-f]{40}", args.commit):
        sys.exit("--commit takes a full 40-digit commit hash")

    themes = []
    for entry in sorted(listing(args.commit, "themes"), key=lambda e: e["name"]):
        if entry["type"] != "dir":
            continue
        slug = entry["name"]
        files = {item["name"] for item in listing(args.commit, f"themes/{slug}") if item["type"] == "file"}
        if "colors.toml" not in files:
            sys.exit(f"themes/{slug} has no colors.toml")
        colors = raw_file(args.commit, f"themes/{slug}/colors.toml")
        shell = raw_file(args.commit, f"themes/{slug}/shell.toml") if "shell.toml" in files else None
        rounding = 0
        if "hyprland.lua" in files:
            match = re.search(r"rounding\s*=\s*(\d+)", raw_file(args.commit, f"themes/{slug}/hyprland.lua"))
            if match:
                rounding = int(match.group(1))
        themes.append((slug, display_name(slug), colors, shell, rounding, "light.mode" in files))
        print(f"{slug}: shell.toml {'yes' if shell is not None else 'no'}, rounding {rounding}, "
              f"light.mode {'yes' if themes[-1][5] else 'no'}")

    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by scripts/import_omarchy_themes.py; do not edit by hand.",
        f"// Omarchy's built-in themes from {REPO} at commit {args.commit}:",
        "// themes/<slug>/colors.toml, shell.toml, the rounding of hyprland.lua and light.mode.",
        "// Copyright (c) David Heinemeier Hansson, MIT License: see third_party/omarchy/LICENSE.",
        "",
        "struct BundledTheme {",
        "    const char* slug;",
        "    const char* name;",
        "    const char* colors;",
        "    const char* shell; // nullptr if none",
        "    int rounding;",
        "    bool lightModeFile;",
        "};",
        "",
        "inline constexpr BundledTheme kBundledThemes[] = {",
    ]
    for slug, name, colors, shell, rounding, light in themes:
        lines.append(f'    {{"{slug}", "{name}",')
        lines.append(f"     {literal(colors)},")
        lines.append(f"     {literal(shell) if shell is not None else 'nullptr'}, {rounding}, "
                     f"{'true' if light else 'false'}}},")
    lines.append("};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(themes)} themes")


if __name__ == "__main__":
    main()
